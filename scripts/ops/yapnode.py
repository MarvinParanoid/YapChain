def rpc_get(base, path, timeout=5):
    with urllib.request.urlopen(base.rstrip("/") + path, timeout=timeout) as r:
        body = json.load(r)
    if "error" in body:
        raise OpsError(f"RPC {path}: {body['error']}")
    return body["result"]


def parse_rfc3339(s):
    """CometBFT times carry nanoseconds; datetime takes at most microseconds."""
    m = re.fullmatch(r"(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d)(?:\.(\d+))?Z", s)
    if not m:
        raise ValueError(f"unexpected time {s!r}")
    frac = (m.group(2) or "0")[:6].ljust(6, "0")
    return datetime.datetime.fromisoformat(f"{m.group(1)}.{frac}+00:00")


def node_status(d, rpc=None, stall_s=30):
    d = os.path.abspath(d)
    node = load_node(d)
    if rpc is None:
        env = dict(line.split("=", 1) for line in open(os.path.join(d, "compose.env")).read().splitlines() if "=" in line)
        host = env.get("RPC_BIND", "127.0.0.1")
        rpc = f"http://{'127.0.0.1' if host in ('0.0.0.0', '') else host}:{env.get('RPC_PORT', '26657')}"
    row = {"node": node["moniker"], "role": node["role"], "dir": d, "rpc": rpc, "containers": {}}
    for c in containers_of(d):
        svc = c["Config"]["Labels"].get("io.yapchain.service", c["Name"])
        st = c["State"]
        row["containers"][svc] = {"name": c["Name"].lstrip("/"), "state": st["Status"],
                                  "health": (st.get("Health") or {}).get("Status", "none"),
                                  "restarts": c.get("RestartCount", 0), "exit_code": st.get("ExitCode")}
    try:
        st = rpc_get(rpc, "/status")
        si = st["sync_info"]
        row.update({"chain_id": st["node_info"]["network"], "height": int(si["latest_block_height"]),
                    "app_hash": si["latest_app_hash"], "catching_up": si["catching_up"],
                    "latest_block_time": si["latest_block_time"]})
        t = parse_rfc3339(si["latest_block_time"])
        age = (datetime.datetime.now(datetime.timezone.utc) - t).total_seconds()
        row["last_block_age_s"] = round(age, 1)
        row["progress"] = "catching_up" if si["catching_up"] else ("stalled" if age > stall_s else "advancing")
        ni = rpc_get(rpc, "/net_info")
        row["peers"] = int(ni["n_peers"])
        row["peer_monikers"] = sorted(p["node_info"]["moniker"] for p in ni["peers"])
        vals = rpc_get(rpc, "/validators?per_page=100")
        power = {v["address"]: int(v["voting_power"]) for v in vals["validators"]}
        row["validator"] = {"in_set": node["validator_address"] in power,
                            "voting_power": power.get(node["validator_address"], 0),
                            "total_power": sum(power.values())}
        q = rpc_get(rpc, '/abci_query?path="/chain"')
        if q["response"].get("code", 0) == 0 and q["response"].get("value"):
            chain = json.loads(base64.b64decode(q["response"]["value"]))
            row["state_root"] = chain.get("state_root")
            row["app_height"] = chain.get("height")
        row["rpc_ready"] = True
    except (OSError, OpsError, ValueError, KeyError, urllib.error.URLError) as e:
        row["rpc_ready"] = False
        row["error"] = str(e)
    return row


def status(d):
    d = os.path.abspath(d)
    if os.path.exists(os.path.join(d, "network.json")):
        net = read_json(os.path.join(d, "network.json"))
        return [node_status(x["dir"], x["rpc"]) for x in net["nodes"].values()]
    return [node_status(d)]


def print_status(rows):
    for r in rows:
        cs = ", ".join(f"{k}={v['state']}/{v['health']}/restarts={v['restarts']}" for k, v in r["containers"].items())
        if not r.get("rpc_ready"):
            print(f"{r['node']:<12} {r['role']:<9} RPC not ready ({r.get('error', '')[:80]}) [{cs or 'no containers'}]")
            continue
        v = r["validator"]
        print(f"{r['node']:<12} {r['role']:<9} chain={r['chain_id']} height={r['height']} {r['progress']}"
              f" (last block {r['last_block_age_s']}s ago) peers={r['peers']} catching_up={r['catching_up']}"
              f" app_hash={r['app_hash'][:16]} state_root={str(r.get('state_root'))[:16]}"
              f" power={v['voting_power']}/{v['total_power']} [{cs}]")


