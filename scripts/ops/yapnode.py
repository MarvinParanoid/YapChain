"""yapnode — build, initialise, configure, inspect, back up and restore containerised YapChain nodes
(M2.7, ADR-0031, docs/operations.md).

Every key, genesis and database operation runs inside the project images (`docker run --rm`, no
network, read-only root, all capabilities dropped) as the node's runtime uid, so the host needs only
Docker and Python 3 (standard library). Nothing here deletes or replaces keys, a genesis, signing
state or a populated database; conflicting input is an error.

  yapnode.py build      [--tag-suffix T] [--platform P] [--out build/images.json]
  yapnode.py init       --dir D --role validator|full --moniker M [--chain-id ID]
  yapnode.py export     --dir D [--reward-address A] [--power N] [--p2p-address HOST:PORT]
  yapnode.py genesis    --chain-id ID --validator FILE... [--account ADDR=AMOUNT...] [--time-ms T] --out G
  yapnode.py configure  --dir D --genesis G [--genesis-sha256 H] [--peer ID@HOST:PORT...] [network options]
  yapnode.py localnet   --dir D [--validators N] [--full-nodes K] [--chain-id ID] [--timeout-commit 1s]
  yapnode.py status     --dir D [--json]            (a node directory or a localnet directory)
  yapnode.py backup     --dir D --out FILE.tar [--include-keys]
  yapnode.py verify-backup FILE.tar
  yapnode.py restore    --archive FILE.tar --dir NEWDIR --as full|validator [validator recovery options]
  yapnode.py signing-floor --dir D --height H

Node directory (0700, owned by the runtime uid):
  node.json      role, chain id, moniker, node id, validator address (public data only)
  compose.env    settings for deploy/compose/node.yml (generated by configure)
  cometbft/      CometBFT home: config/ (keys, genesis, config.toml; mounted read-only) and data/
  yapd/          yapd home: data/ is the LMDB database (yap.lock = exclusive writer lock)
  abci/          the ABCI Unix socket shared by this node's two containers only
Run with `python3 -I`.
"""
