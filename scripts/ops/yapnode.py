LOCAL_ACCOUNTS = {"alice": "1000000YAP", "bob": "1000YAP", "carol": "1000YAP", "dave": "10YAP"}


def localnet_init(d, validators=4, full_nodes=0, chain_id="yapchain-docker-1", timeout_commit="1s", uid=None,
                  gid=None, rpc_port_base=26657, extra_accounts=None, project="yapnet", subnet_prefix="172.31.250"):
    """A containerised local network: N validators (+ K full nodes) on one Docker network, created
    with the same init/export/genesis/configure steps an operator uses on separate hosts. Test wallet
    keys (dev only) are created in D/wallet with a random password in D/wallet.password (0600)."""
    d = os.path.abspath(d)
    if os.path.exists(os.path.join(d, "network.json")):
        raise OpsError(f"{d} already holds a network")
    if validators < 1 or validators > 4 or full_nodes < 0 or full_nodes > 1:
        raise OpsError("deploy/compose supports 1 or 4 validators and at most 1 full node")
    if validators not in (1, 4):
        raise OpsError("--validators must be 1 (compose A) or 4 (compose B/C)")
    uid, gid = runtime_ids(uid, gid)
    os.makedirs(d, mode=0o700, exist_ok=True)
    names = [f"validator{i}" for i in range(validators)] + [f"fullnode{i}" for i in range(full_nodes)]
    nodes = {}
    for n in names:
        role = "validator" if n.startswith("validator") else "full"
        nodes[n] = init(os.path.join(d, n), role, n, chain_id, uid, gid)
    wallet = os.path.join(d, "wallet")
    os.makedirs(wallet, mode=0o700, exist_ok=True)
    pw = os.path.join(d, "wallet.password")
    if not os.path.exists(pw):
        fd = os.open(pw, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(secrets.token_hex(24) + "\n")
    if os.geteuid() == 0:
        os.chown(wallet, uid, gid)
        os.chown(pw, uid, gid)
    wmounts = [(wallet, "/wallet", "rw"), (pw, "/wallet.password", "ro")]
    addrs = {}
    rewards = [f"reward-{n}" for n in names if n.startswith("validator")]
    for name in list(LOCAL_ACCOUNTS) + rewards:
        r = yap(["--home", "/wallet", "--password-file", "/wallet.password", "keys", "create", name], wmounts, uid, gid)
        addrs[name] = localnet.kv(r.stdout)["address"]
    exports = [export(os.path.join(d, n), reward_address=addrs[f"reward-{n}"]) for n in names if n.startswith("validator")]
    accounts = {addrs[k]: v for k, v in LOCAL_ACCOUNTS.items()}
    accounts.update(extra_accounts or {})
    gpath = os.path.join(d, "genesis.json")
    digest, ghash = make_genesis(chain_id, exports, accounts, gpath, uid=uid, gid=gid)
    if not re.fullmatch(r"(\d{1,3}\.){2}\d{1,3}", subnet_prefix):
        raise OpsError("--subnet-prefix: three octets, e.g. 172.31.250")
    ips = {n: f"{subnet_prefix}.{10 + int(n[-1]) if n.startswith('validator') else 20 + int(n[-1])}" for n in names}
    for i, n in enumerate(names):
        # Addresses, not host names: CometBFT resolves persistent peers once at start-up and drops a name
        # that does not resolve yet (a peer container that is not up) until it is restarted.
        peers = [f"{nodes[p]['node_id']}@{ips[p]}:26656" for p in names if p != n and p.startswith("validator")]
        configure(os.path.join(d, n), gpath, digest, peers, rpc_port=rpc_port_base + 10 * i, publish_p2p=False,
                  timeout_commit=timeout_commit, private_network=True, peer_dial_period="2s",
                  project=project)
    net = {"chain_id": chain_id, "genesis_sha256": digest, "genesis_hash": ghash, "validators": validators,
           "full_nodes": full_nodes, "nodes": {n: {"dir": os.path.join(d, n), "node_id": nodes[n]["node_id"],
                                                  "role": nodes[n]["role"],
                                                  "validator_address": nodes[n]["validator_address"],
                                                  "rpc": f"http://127.0.0.1:{rpc_port_base + 10 * i}", "ip": ips[n]}
                                              for i, n in enumerate(names)},
           "addresses": addrs, "wallet": wallet, "password_file": pw, "uid": uid, "gid": gid}
    write_json(os.path.join(d, "network.json"), net)
    env = {"NET_DIR": d, "YAP_UID": uid, "YAP_GID": gid, "YAPCHAIN_IMAGE": YAPCHAIN_IMAGE,
           "COMETBFT_IMAGE": COMETBFT_IMAGE, "RPC_BIND": "127.0.0.1", "COMPOSE_PROJECT_NAME": project,
           "YAPNET_PREFIX": subnet_prefix}
    for i, n in enumerate(names):
        env[f"RPC_PORT_{n.upper()}"] = rpc_port_base + 10 * i
    write_atomic(os.path.join(d, "compose.env"), "".join(f"{k}={v}\n" for k, v in env.items()), 0o600)
    return net


