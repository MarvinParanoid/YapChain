KEY_FILES = ("cometbft/config/priv_validator_key.json", "cometbft/config/node_key.json")


def _verify_state(yapd_dir, uid, gid):
    r = yap(["--home", "/var/lib/yapd", "verify-state"], [(yapd_dir, "/var/lib/yapd", "ro")], uid, gid, check=False)
    if r.returncode != 0:
        raise OpsError(f"verify-state failed: {r.stdout}{r.stderr}".strip())
    return localnet.kv(r.stdout)


def backup(d, out, include_keys=False):
    """Offline backup: the node's containers must be stopped, and yapd's writer lock is held for the
    whole copy. The application database is verified (verify-state) before it is archived. Private
    keys are excluded unless include_keys; the archive is written 0600 and atomically."""
    d = os.path.abspath(d)
    node = load_node(d)
    require_stopped(d)
    if os.path.exists(out):
        raise OpsError(f"{out} exists; refusing to overwrite a backup")
    data_dir = os.path.join(d, "yapd", "data")
    with LmdbLock(data_dir):
        vs = _verify_state(os.path.join(d, "yapd"), node["uid"], node["gid"]) if os.path.isdir(data_dir) else {}
        files = []
        for base in ("node.json", "compose.env", "cometbft", "yapd"):
            p = os.path.join(d, base)
            if os.path.isfile(p):
                files.append(base)
            elif os.path.isdir(p):
                for root, _, fs in os.walk(p):
                    for f in fs:
                        rel = os.path.relpath(os.path.join(root, f), d)
                        if rel.endswith("yap.lock") or rel.endswith(".prev"):
                            continue
                        files.append(rel)
        if not include_keys:
            files = [f for f in files if f not in KEY_FILES]
        manifest = {"format": "yapnode-backup/1", "node": node, "created_utc":
                    datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                    "includes_private_keys": include_keys, "verify_state": vs,
                    "files": {f: sha256_file(os.path.join(d, f)) for f in sorted(files)}}
        tmp = out + ".partial"
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        try:
            with os.fdopen(fd, "wb") as fobj, tarfile.open(fileobj=fobj, mode="w") as t:
                m = json.dumps(manifest, indent=2, sort_keys=True).encode()
                ti = tarfile.TarInfo("MANIFEST.json")
                ti.size, ti.mode, ti.mtime = len(m), 0o600, int(time.time())
                t.addfile(ti, io.BytesIO(m))
                for f in sorted(files):
                    t.add(os.path.join(d, f), arcname=f"node/{f}", recursive=False)
                fobj.flush()
                os.fsync(fobj.fileno())
            os.replace(tmp, out)
        except BaseException:
            try:
                os.remove(tmp)
            except FileNotFoundError:
                pass
            raise
    # The archive must match what was hashed under the lock.
    verify_backup(out)
    log(f"backup {out}: height {vs.get('height')} state root {vs.get('state_root')}, {len(files)} files, "
        f"private keys {'INCLUDED' if include_keys else 'excluded'}")
    return manifest


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def verify_backup(archive):
    with tarfile.open(archive) as t:
        manifest = json.load(t.extractfile("MANIFEST.json"))
        seen = {}
        for m in t.getmembers():
            if m.name == "MANIFEST.json":
                continue
            if not m.isfile() or not m.name.startswith("node/") or ".." in m.name.split("/"):
                raise OpsError(f"{archive}: unexpected member {m.name}")
            h = hashlib.sha256()
            f = t.extractfile(m)
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
            seen[m.name[5:]] = h.hexdigest()
    if seen != manifest["files"]:
        raise OpsError(f"{archive}: content differs from its manifest")
    return manifest


def restore(archive, d, as_role, validator_key=None, signing_floor=None, original_decommissioned=False, uid=None,
            gid=None):
    """Restores a backup into a NEW directory. as_role full: the node gets a fresh validator key that is
    in no validator set and a fresh node key unless the backup had one (never signs). as_role
    validator: allowed only with the validator key file, an explicit signing floor height and the
    explicit statement that the original validator is decommissioned; the signing state is raised to
    the floor so nothing at or below it can be signed (docs/operations.md, validator recovery)."""
    manifest = verify_backup(archive)
    d = os.path.abspath(d)
    if os.path.exists(d) and os.listdir(d):
        raise OpsError(f"{d} exists and is not empty; restore only into a new directory")
    if as_role == "validator":
        if not (validator_key and signing_floor is not None and original_decommissioned):
            raise OpsError("validator recovery needs --validator-key, --signing-floor-height and "
                           "--original-decommissioned (read docs/operations.md first)")
    elif as_role != "full":
        raise OpsError("--as must be full or validator")
    node = dict(manifest["node"])
    uid, gid = runtime_ids(uid if uid is not None else node.get("uid"), gid if gid is not None else node.get("gid"))
    parent = os.path.dirname(d)
    os.makedirs(parent, exist_ok=True)
    tmp = tempfile.mkdtemp(prefix=f".{os.path.basename(d)}.restore-", dir=parent)
    try:
        with tarfile.open(archive) as t:
            for m in t.getmembers():
                if m.name == "MANIFEST.json":
                    continue
                rel = m.name[5:]
                if as_role == "full" and rel == KEY_FILES[0]:
                    continue
                dst = os.path.join(tmp, rel)
                os.makedirs(os.path.dirname(dst), mode=0o700, exist_ok=True)
                with t.extractfile(m) as src, open(dst, "wb") as out:
                    shutil.copyfileobj(src, out)
                os.chmod(dst, 0o600 if rel in KEY_FILES or rel.endswith("priv_validator_state.json") else 0o644)
        for sub in ("cometbft/config", "cometbft/data", "yapd", "abci"):
            os.makedirs(os.path.join(tmp, sub), mode=0o700, exist_ok=True)
        cfg = os.path.join(tmp, "cometbft", "config")
        if os.geteuid() == 0:
            for root, dirs, fs in os.walk(tmp):
                os.chown(root, uid, gid)
                for x in dirs + fs:
                    os.chown(os.path.join(root, x), uid, gid)
        os.chmod(tmp, 0o700)
        mounts = [(os.path.join(tmp, "cometbft"), CMT, "rw")]
        if as_role == "full":
            # A fresh, unused validator key; the old one never leaves the archive.
            fresh = tempfile.mkdtemp(prefix="yapnode-key-")
            try:
                os.chmod(fresh, 0o777)
                cometbft(["init", "--home", "/k"], [(fresh, "/k", "rw")], uid, gid)
                shutil.copyfile(os.path.join(fresh, "config", "priv_validator_key.json"),
                                os.path.join(cfg, "priv_validator_key.json"))
                os.chmod(os.path.join(cfg, "priv_validator_key.json"), 0o600)
                if not os.path.exists(os.path.join(cfg, "node_key.json")):
                    shutil.copyfile(os.path.join(fresh, "config", "node_key.json"), os.path.join(cfg, "node_key.json"))
                    os.chmod(os.path.join(cfg, "node_key.json"), 0o600)
            finally:
                shutil.rmtree(fresh, ignore_errors=True)
            pvs = os.path.join(tmp, "cometbft", "data", "priv_validator_state.json")
            write_json(pvs, {"height": "0", "round": 0, "step": 0}, 0o600)  # the fresh key has signed nothing
            pv = read_json(os.path.join(cfg, "priv_validator_key.json"))
            node["role"] = "full"
            node["validator_address"] = pv["address"]
            node["validator_pubkey"] = base64.b64decode(pv["pub_key"]["value"]).hex()
        else:
            shutil.copyfile(validator_key, os.path.join(cfg, "priv_validator_key.json"))
            os.chmod(os.path.join(cfg, "priv_validator_key.json"), 0o600)
            pv = read_json(os.path.join(cfg, "priv_validator_key.json"))
            if pv["address"] != node["validator_address"]:
                raise OpsError("the validator key does not belong to the backed-up node")
            _raise_floor(os.path.join(tmp, "cometbft", "data", "priv_validator_state.json"), int(signing_floor))
        if not os.path.exists(os.path.join(cfg, "node_key.json")):
            raise OpsError("the backup has no node key; restore with --as full (a new node key is created)")
        node["node_id"] = cometbft(["show-node-id", "--home", CMT], mounts, uid, gid).stdout.strip()
        node.update({"uid": uid, "gid": gid, "restored_from": os.path.basename(archive),
                     "restored_utc": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")})
        write_json(os.path.join(tmp, "node.json"), node)
        try:
            os.remove(os.path.join(tmp, "compose.env"))  # ports/paths belong to the old host: configure again
        except FileNotFoundError:
            pass
        vs = _verify_state(os.path.join(tmp, "yapd"), uid, gid) if os.path.isdir(os.path.join(tmp, "yapd", "data")) else {}
        want = manifest.get("verify_state", {})
        if vs.get("state_root") != want.get("state_root") or vs.get("height") != want.get("height"):
            raise OpsError(f"restored database verifies as {vs}, backup recorded {want}")
        if os.path.exists(d):
            os.rmdir(d)
        os.rename(tmp, d)
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    log(f"restored {archive} into {d} as {as_role}: height {vs.get('height')} state root {vs.get('state_root')}")
    return node, vs


def _raise_floor(path, height):
    """priv_validator_state: never lowered. A floor at height H = (H, round int32 max, step precommit) and
    no stored signature: CometBFT's FilePV then refuses every vote and proposal at heights <= H (height
    regression below H, round regression at H) and signs normally from H+1."""
    cur = read_json(path) if os.path.exists(path) else {"height": "0", "round": 0, "step": 0}
    cur_h = int(cur.get("height", "0"))
    if height < cur_h or (height == cur_h and int(cur.get("round", 0)) == MAX_ROUND):
        log(f"signing state already at height {cur_h}; not lowered")
        return cur
    new = {"height": str(height), "round": MAX_ROUND, "step": 3}
    write_json(path, new, 0o600)
    return new


def signing_floor(d, height):
    d = os.path.abspath(d)
    load_node(d)
    require_stopped(d)
    return _raise_floor(os.path.join(d, "cometbft", "data", "priv_validator_state.json"), int(height))


